#!/usr/bin/env python3
"""Build preview/: the real frontend running against an in-browser mock API.

Browsers refuse to load ES modules from file://, so the preview concatenates
the app's modules into classic scripts with a tiny module shim (the served app
itself still uses native ES modules with no build step). Everything else
(CSS, fonts, icons) is copied verbatim, so the preview is the actual UI.

Usage: python scripts/build_preview.py   (needs ffmpeg for the sample clips)
"""
from __future__ import annotations

import base64
import json
import posixpath
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "backend" / "homelib" / "static"
OUT = ROOT / "preview"
sys.path.insert(0, str(ROOT / "backend"))

from homelib import mock, text  # noqa: E402

IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$", re.M)
EXPORT_RE = re.compile(r"^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)

RUNTIME = """(function () {
  if (window.__hl_require) return;
  var defs = {}, cache = {};
  window.__hl_define = function (name, fn) { defs[name] = fn; };
  window.__hl_require = function req(name) {
    if (cache[name]) return cache[name];
    if (!defs[name]) throw new Error('module not bundled: ' + name);
    var exp = cache[name] = {};
    defs[name](exp, req);
    return exp;
  };
})();
"""


def bundle(entry: Path, base: Path) -> str:
    """Concatenate entry and its (static, named) imports into one classic script."""
    seen: dict[str, str] = {}

    def visit(path: Path) -> None:
        name = path.relative_to(base).as_posix()
        if name in seen:
            return
        src = path.read_text()
        seen[name] = ""  # mark before recursing (no cycles expected)
        reqs = []
        for names, spec in IMPORT_RE.findall(src):
            dep = posixpath.normpath(posixpath.join(posixpath.dirname(name), spec))
            visit(base / dep)
            binds = ", ".join(n.strip().replace(" as ", ": ") for n in names.split(",") if n.strip())
            reqs.append(f"  const {{ {binds} }} = __require({json.dumps(dep)});")
        body = IMPORT_RE.sub("", src)
        exports = [m[1] for m in EXPORT_RE.findall(body)]
        body = EXPORT_RE.sub(lambda m: f"{m.group(1)} {m.group(2)}", body)
        seen[name] = (f"__hl_define({json.dumps(name)}, function (__exports, __require) {{\n"
                      + "\n".join(reqs) + "\n" + body
                      + f"\n  Object.assign(__exports, {{ {', '.join(exports)} }});\n}});\n")

    visit(entry)
    entry_name = entry.relative_to(base).as_posix()
    return ("// Generated by scripts/build_preview.py – do not edit.\n" + RUNTIME
            + "".join(seen.values()) + f"__hl_require({json.dumps(entry_name)});\n")


def make_clips(media: Path) -> None:
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        try:
            import imageio_ffmpeg

            ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        except Exception:
            print("!! ffmpeg not found: preview will have no playable clips")
            return
    media.mkdir(parents=True, exist_ok=True)
    sources = ["testsrc2", "smptehdbars", "rgbtestsrc"]
    tones = [330, 440, 550]
    for kind, size in (("landscape", "640x360"), ("vertical", "360x640")):
        for i, (src, tone) in enumerate(zip(sources, tones), start=1):
            out = media / f"{kind}-{i}.mp4"
            if out.exists():
                continue
            subprocess.run([ffmpeg, "-y", "-loglevel", "error",
                            "-f", "lavfi", "-i", f"{src}=size={size}:rate=24:duration=8",
                            "-f", "lavfi", "-i", f"sine=frequency={tone}:duration=8",
                            "-vf", "hue=h=" + str(i * 40),
                            "-c:v", "libx264", "-preset", "veryfast", "-crf", "32", "-pix_fmt", "yuv420p",
                            "-c:a", "aac", "-b:a", "48k", "-shortest", "-movflags", "+faststart", str(out)],
                           check=True)


def make_songs(media: Path, ffmpeg: str | None) -> None:
    """Three short sample 'songs' (simple chords) for the Music page."""
    chords = [(262, 330, 392), (220, 277, 330), (196, 247, 294)]
    for i, (a, b, c) in enumerate(chords, start=1):
        out = media / f"song-{i}.mp3"
        if out.exists() or not ffmpeg:
            continue
        expr = f"0.2*sin({a}*2*PI*t)+0.2*sin({b}*2*PI*t)+0.2*sin({c}*2*PI*t)"
        subprocess.run([ffmpeg, "-y", "-loglevel", "error", "-f", "lavfi", "-i", f"aevalsrc='{expr}':d=12",
                        "-af", "afade=t=in:d=1,afade=t=out:st=10:d=2", "-c:a", "libmp3lame", "-b:a", "96k", str(out)],
                       check=True)


def main() -> None:
    if OUT.exists():
        keep_media = OUT / "media"
        tmp = None
        if keep_media.exists():  # regenerating clips is slow; keep them
            tmp = ROOT / ".preview-media-tmp"
            shutil.rmtree(tmp, ignore_errors=True)
            keep_media.rename(tmp)
        shutil.rmtree(OUT)
        OUT.mkdir()
        if tmp:
            tmp.rename(OUT / "media")
    else:
        OUT.mkdir()
    for d in ("css", "fonts", "icons"):
        shutil.copytree(STATIC / d, OUT / d)
    # file:// pages can't fetch fonts (CORS), so inline them into the preview CSS.
    css = (OUT / "css" / "app.css").read_text()
    css = re.sub(r'url\("\.\./fonts/([^"]+)"\)',
                 lambda m: "url(data:font/woff2;base64,"
                 + base64.b64encode((STATIC / "fonts" / m.group(1)).read_bytes()).decode() + ")", css)
    (OUT / "css" / "app.css").write_text(css)

    (OUT / "app.bundle.js").write_text(bundle(STATIC / "js" / "app.js", STATIC))
    (OUT / "mockapi.bundle.js").write_text(bundle(ROOT / "preview_src" / "mockapi.js", ROOT / "preview_src"))

    catalog = []
    for v in mock.CATALOG:
        item = mock.public(v)
        item["keywords"] = text.keywords(v["title"])
        catalog.append(item)
    songs = [mock.public(v) for v in mock.SONG_CATALOG]
    (OUT / "mockdata.js").write_text(
        "// Generated from backend/homelib/mock.py by scripts/build_preview.py\n"
        "window.HOMELIB_MOCK_DATA = " + json.dumps({"catalog": catalog, "songs": songs}, indent=1) + ";\n")

    thumbs = OUT / "thumbs"
    thumbs.mkdir()
    for v in mock.CATALOG + mock.SONG_CATALOG:
        (thumbs / f"{v['id']}.svg").write_text(mock.thumbnail_svg(v["id"]))
    make_clips(OUT / "media")
    make_songs(OUT / "media", shutil.which("ffmpeg"))

    html = (STATIC / "index.html").read_text()
    html = html.replace('  <link rel="manifest" href="manifest.webmanifest">\n', "")
    html = re.sub(r'  <link rel="preload"[^>]*>\n', "", html)
    html = html.replace('<title>Home Video Library</title>', '<title>Home Video Library – preview</title>')
    html = html.replace(
        '  <script type="module" src="js/app.js"></script>',
        '  <!-- Preview build: mock data + in-browser fake API, no server needed. -->\n'
        '  <script src="mockdata.js"></script>\n  <script src="mockapi.bundle.js"></script>\n'
        '  <script src="app.bundle.js"></script>')
    (OUT / "index.html").write_text(html)
    (OUT / "README.md").write_text(
        "# Home Video Library – static preview\n\n"
        "Open `index.html` in a browser (double-click works; no server needed).\n"
        "For the phone-sized view, use your browser's device toolbar at 390px width.\n\n"
        "Everything runs against an in-browser mock of the server API with fake YouTube data.\n"
        "Clicks are saved in localStorage; Settings → \"Reset demo data\" starts over.\n\n"
        "Generated by `python scripts/build_preview.py` from `backend/homelib/static/` – don't edit by hand.\n")
    print(f"preview built in {OUT}")


if __name__ == "__main__":
    main()
