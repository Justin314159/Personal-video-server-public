#!/usr/bin/env python3
"""Write packaging/pins/embeddings-cp3XX.txt: the optional MiniLM add-on
(fastembed and everything it adds), locked to exact versions and SHA-256
hashes, for each Python version the USB package supports.

install_embeddings.sh installs exactly these files with
`pip install --no-deps --require-hashes --only-binary=:all:`, so nothing
unexpected (a newer release, a changed file, a source package that runs code
at install time) can get in. Packages the app already has are left out: they
stay at the versions in packaging/pins/constraints-cp3XX.txt.

Needs internet (PyPI). Run it when changing FASTEMBED below or the base pins:
    python3 scripts/pin_embeddings.py
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINS = ROOT / "packaging" / "pins"
FASTEMBED = "fastembed==0.9.1"
VERSIONS = ["3.10", "3.11", "3.12", "3.13", "3.14"]
PLATFORMS = ["manylinux2014_x86_64", "manylinux_2_17_x86_64", "manylinux_2_24_x86_64", "manylinux_2_27_x86_64",
             "manylinux_2_28_x86_64", "manylinux_2_31_x86_64", "manylinux_2_34_x86_64", "manylinux_2_35_x86_64"]


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def base_pins(tag: str) -> dict[str, str]:
    out = {}
    for line in (PINS / f"constraints-cp{tag}.txt").read_text().split():
        if "==" in line:
            n, v = line.split("==", 1)
            out[norm(n)] = v
    return out


def wheel_ok(filename: str, tag: str) -> bool:
    """A wheel pip could pick on Linux x86_64 with CPython 3.<tag[1:]>."""
    if not filename.endswith(".whl"):
        return False
    py, abi, plat = filename[:-4].split("-")[-3:]
    if plat != "any" and not ("x86_64" in plat and ("manylinux" in plat or "linux" == plat.split("_")[0])):
        return False
    pys = py.split(".")
    if any(p in ("py3", "py2.py3") for p in pys) or "py3" in pys:
        return True
    if f"cp{tag}" in pys:
        return True
    if abi == "abi3":
        return any(p.startswith("cp3") and int(p[3:]) <= int(tag[1:]) for p in pys)
    return False


def hashes(name: str, version: str, tag: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        data = json.load(r)
    out = sorted(u["digests"]["sha256"] for u in data["urls"] if wheel_ok(u["filename"], tag))
    if not out:
        raise SystemExit(f"no Linux x86_64 wheel of {name} {version} for cp{tag}")
    return out


def main() -> None:
    cache = ROOT / "build" / "embedding-wheels"
    cache.mkdir(parents=True, exist_ok=True)
    for v in VERSIONS:
        tag = v.replace(".", "")
        base = base_pins(tag)
        with tempfile.TemporaryDirectory() as tmp:
            plat = [a for p in PLATFORMS for a in ("--platform", p)]
            subprocess.run([sys.executable, "-m", "pip", "download", "-q", "--disable-pip-version-check",
                            FASTEMBED, "-c", str(PINS / f"constraints-cp{tag}.txt"), "--only-binary=:all:",
                            *plat, "--python-version", v, "--implementation", "cp", "-d", tmp], check=True)
            found = {}
            for whl in Path(tmp).glob("*.whl"):
                n, ver = whl.name.split("-")[:2]
                found[norm(n)] = ver
        lines = [f"# fastembed for the MiniLM add-on, CPython {v} on Linux x86_64.",
                 "# Generated by scripts/pin_embeddings.py; installed by install_embeddings.sh with",
                 "# --no-deps --require-hashes. Packages the app already has are not listed."]
        for n in sorted(found):
            if n in base:
                if base[n] != found[n]:
                    raise SystemExit(f"cp{tag}: fastembed wants {n} {found[n]}, the app pins {base[n]}")
                continue
            lines.append(f"{n}=={found[n]} \\")
            hs = hashes(n, found[n], tag)
            lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
        (PINS / f"embeddings-cp{tag}.txt").write_text("\n".join(lines) + "\n")
        print(f"cp{tag}: {len([l for l in lines if '==' in l])} packages")


if __name__ == "__main__":
    main()
